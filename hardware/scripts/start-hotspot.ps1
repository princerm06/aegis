<#
.SYNOPSIS
  Turn this laptop into the WiFi network the responder Arduino joins.

.DESCRIPTION
  Uses Windows Mobile Hotspot on 2.4 GHz (the only band the UNO R4 WiFi has).
  The hotspot name and password come from the git-ignored
  hardware/firmware/aegis_responder/arduino_secrets.h, which the firmware is
  compiled with, so the laptop and the Arduino always agree. If that file does
  not exist yet it is created with a random password; then re-flash the Arduino.

  The laptop is always 192.168.137.1 on its own hotspot, which is where the
  firmware connects (BRIDGE_HOST). Run the bridge with --wifi afterwards.

  Check that your university allows personal hotspots: Windows Mobile Hotspot
  shares the laptop's current connection (e.g. eduroam) with the hotspot. A
  phone hotspot is the alternative (see hardware/README.md).

.EXAMPLE
  .\hardware\scripts\start-hotspot.ps1           # configure + start
.EXAMPLE
  .\hardware\scripts\start-hotspot.ps1 -Status   # show state, change nothing
.EXAMPLE
  .\hardware\scripts\start-hotspot.ps1 -Stop
#>
param([switch]$Status, [switch]$Stop)

$ErrorActionPreference = "Stop"
$secretsPath = Join-Path $PSScriptRoot "..\firmware\aegis_responder\arduino_secrets.h"
$devicePort = 7777
$devicePorts = "7777-7780"   # device N connects to 7777 + N - 1

Add-Type -AssemblyName System.Runtime.WindowsRuntime
$null = [Windows.Networking.Connectivity.NetworkInformation, Windows.Networking.Connectivity, ContentType = WindowsRuntime]
$null = [Windows.Networking.NetworkOperators.NetworkOperatorTetheringManager, Windows.Networking.NetworkOperators, ContentType = WindowsRuntime]

$asTaskMethods = [System.WindowsRuntimeSystemExtensions].GetMethods() |
    Where-Object { $_.Name -eq "AsTask" -and $_.GetParameters().Count -eq 1 }
function Await-Operation($operation, [Type]$resultType) {
    $generic = $asTaskMethods | Where-Object { $_.GetParameters()[0].ParameterType.Name -eq 'IAsyncOperation`1' } |
        Select-Object -First 1
    $task = $generic.MakeGenericMethod($resultType).Invoke($null, @($operation))
    $null = $task.Wait(-1)
    return $task.Result
}
function Await-Action($action) {
    $plain = $asTaskMethods | Where-Object { $_.GetParameters()[0].ParameterType.Name -eq "IAsyncAction" } |
        Select-Object -First 1
    $task = $plain.Invoke($null, @($action))
    $null = $task.Wait(-1)
}

function Read-Secrets {
    if (-not (Test-Path $secretsPath)) { return $null }
    $text = Get-Content $secretsPath -Raw
    $ssid = [regex]::Match($text, '#define\s+SECRET_SSID\s+"([^"]*)"').Groups[1].Value
    $pass = [regex]::Match($text, '#define\s+SECRET_PASS\s+"([^"]*)"').Groups[1].Value
    if (-not $ssid -or $pass.Length -lt 8) { throw "arduino_secrets.h needs SECRET_SSID and an 8+ character SECRET_PASS" }
    return @{ Ssid = $ssid; Pass = $pass }
}

function New-Secrets {
    $chars = "abcdefghjkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789"
    $pass = -join (1..14 | ForEach-Object { $chars[(Get-Random -Maximum $chars.Length)] })
    $content = @"
// Generated by hardware/scripts/start-hotspot.ps1. Git-ignored: never commit.
#define SECRET_SSID "AEGIS-RESPONDER"
#define SECRET_PASS "$pass"
#define BRIDGE_HOST "192.168.137.1"
#define BRIDGE_PORT $devicePort
"@
    Set-Content -Path $secretsPath -Value $content -Encoding ASCII
    Write-Host "Created $secretsPath with a new hotspot password." -ForegroundColor Yellow
    Write-Host "Re-flash the Arduino so it knows it:" -ForegroundColor Yellow
    Write-Host "  arduino-cli compile --upload --fqbn arduino:renesas_uno:unor4wifi -p COM13 hardware/firmware/aegis_responder"
    Write-Host "  (if it says 'No device found', double-tap the board's RESET button and run it again)"
    return @{ Ssid = "AEGIS-RESPONDER"; Pass = $pass }
}

$profile = [Windows.Networking.Connectivity.NetworkInformation]::GetInternetConnectionProfile()
if (-not $profile) { throw "This laptop has no internet connection; Windows Mobile Hotspot needs one to share." }
$manager = [Windows.Networking.NetworkOperators.NetworkOperatorTetheringManager]::CreateFromConnectionProfile($profile)
$config = $manager.GetCurrentAccessPointConfiguration()

if ($Status) {
    Write-Host "Sharing connection : $($profile.ProfileName)"
    Write-Host "Hotspot state      : $($manager.TetheringOperationalState)"
    Write-Host "Hotspot name/band  : $($config.Ssid) / $($config.Band)"
    Write-Host "Clients connected  : $($manager.ClientCount) of $($manager.MaxClientCount)"
    $secrets = Read-Secrets
    if ($secrets) { Write-Host "Arduino expects    : $($secrets.Ssid)" } else { Write-Host "Arduino expects    : (no arduino_secrets.h yet: USB-only firmware)" }
    exit 0
}

if ($Stop) {
    $result = Await-Operation ($manager.StopTetheringAsync()) ([Windows.Networking.NetworkOperators.NetworkOperatorTetheringOperationResult])
    Write-Host "Hotspot stop: $($result.Status)"
    exit 0
}

$secrets = Read-Secrets
if (-not $secrets) { $secrets = New-Secrets }

$config.Ssid = $secrets.Ssid
$config.Passphrase = $secrets.Pass
try {
    $config.Band = [Windows.Networking.NetworkOperators.TetheringWiFiBand]::TwoPointFourGigahertz
} catch {
    Write-Host "This Windows build cannot force 2.4 GHz; set 'Band: 2.4 GHz' in Settings > Mobile hotspot." -ForegroundColor Yellow
}
Await-Action ($manager.ConfigureAccessPointAsync($config))

if ($manager.TetheringOperationalState -ne "On") {
    $result = Await-Operation ($manager.StartTetheringAsync()) ([Windows.Networking.NetworkOperators.NetworkOperatorTetheringOperationResult])
    if ($result.Status -ne "Success") { throw "Could not start the hotspot: $($result.Status) $($result.AdditionalErrorMessage)" }
}

# Let the Arduino reach the bridge port from the hotspot (needs an admin shell; harmless if it exists).
$rule = Get-NetFirewallRule -DisplayName "AEGIS responder bridge" -ErrorAction SilentlyContinue
$open = if ($rule) { ($rule | Get-NetFirewallPortFilter).LocalPort } else { $null }
if ("$open" -ne $devicePorts) {
    try {
        if ($rule) { $rule | Set-NetFirewallRule -LocalPort $devicePorts }
        else {
            New-NetFirewallRule -DisplayName "AEGIS responder bridge" -Direction Inbound -Protocol TCP `
                -LocalPort $devicePorts -RemoteAddress 192.168.137.0/24 -Action Allow | Out-Null
        }
        Write-Host "Firewall: allowed TCP $devicePorts from the hotspot only."
    } catch {
        Write-Host "Firewall rule not added (not an admin shell). When Windows asks about Python, click Allow." -ForegroundColor Yellow
    }
}

Write-Host "Hotspot '$($secrets.Ssid)' is ON at 2.4 GHz; laptop address 192.168.137.1." -ForegroundColor Green
Write-Host "Power the Arduino from a USB power bank, then run:  .\hardware\scripts\start-bridge.ps1 -Wifi -Backend <name>"
